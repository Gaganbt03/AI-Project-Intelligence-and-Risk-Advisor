"""DOCX export for generated documentation.

Why a separate exporter instead of converting the Markdown: the specification asks
for a clean, editable deliverable. A Markdown-to-DOCX conversion inherits the
renderer's emphasis markers and table pipes; building the document from the same
``payload`` the Markdown renderer reads gives real Word headings, real tables and
real bullet lists, with no markup leaking into the file.

The export is deterministic and read-only: it never re-runs generation and never
touches the database, so a download cannot change what is stored.
"""

from __future__ import annotations

import io
from datetime import datetime, timezone

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

from app.services.milestone3.common import (
    DOC_ACTION_ITEMS,
    DOC_RISK_REGISTER,
    DOC_USER_STORIES,
    NOT_SPECIFIED,
)
from app.services.milestone3.documentation.renderer import VERDICT_LABELS

#: Placeholder cells are greyed out rather than dropped, so a reader can see at a
#: glance that the field exists and simply is not in the project data.
_PLACEHOLDER_RGB = RGBColor(0x70, 0x70, 0x70)
_CONFLICT_RGB = RGBColor(0xA6, 0x3D, 0x00)


def _is_placeholder(value: str | None) -> bool:
    v = (value or "").strip()
    return not v or v == NOT_SPECIFIED


def _clean(value: str | None) -> str:
    v = (value or "").strip()
    return v if v else NOT_SPECIFIED


def _run(paragraph, text: str, *, italic: bool = False, mono: bool = False):
    """Add a run, styling explicit placeholders and conflict notes distinctly."""
    run = paragraph.add_run(text)
    if _is_placeholder(text):
        run.italic = True
        run.font.color.rgb = _PLACEHOLDER_RGB
    elif text.startswith("Conflict:") or "conflict" in text.lower() and "preserved" in text.lower():
        run.font.color.rgb = _CONFLICT_RGB
    if mono:
        run.font.name = "Consolas"
        run.font.size = Pt(9)
    return run


def _heading(doc, text: str, level: int = 1) -> None:
    doc.add_heading(text, level=level)


def _kv(doc, label: str, value: str | None, *, mono: bool = False) -> None:
    paragraph = doc.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(2)
    run = paragraph.add_run(f"{label}: ")
    run.bold = True
    _run(paragraph, _clean(value), mono=mono)


def _relationship(doc, label: str, items: list | None) -> None:
    rendered = _labels(items)
    _kv(doc, label, "; ".join(rendered) if rendered else NOT_SPECIFIED)


def _labels(items: list | None) -> list[str]:
    out: list[str] = []
    for item in items or []:
        if isinstance(item, dict):
            title = (item.get("title") or "").strip()
            identifier = (item.get("id") or "").strip()
            out.append(f"{identifier} — {title}" if title else identifier)
        else:
            out.append(str(item))
    return out


#: Table style used for every table. Falls back to plain borders when the running
#: python-docx default template does not carry the named accent style.
_TABLE_STYLE = "Light Grid Accent 1"


def _table(doc, headers: list[str], rows: list[list[str]]) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    try:
        table.style = _TABLE_STYLE
    except KeyError:
        table.style = "Table Grid"
    for cell, text in zip(table.rows[0].cells, headers):
        cell.text = ""
        run = cell.paragraphs[0].add_run(text)
        run.bold = True
    for row in rows:
        cells = table.add_row().cells
        for cell, text in zip(cells, row):
            cell.text = ""
            _run(cell.paragraphs[0], _clean(text))


def _header_block(doc, title: str, project_name: str, basis: str, data: dict | None = None) -> None:
    _heading(doc, title, level=0)
    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = subtitle.add_run(project_name or "Project")
    run.bold = True
    run.font.size = Pt(13)

    due = (data or {}).get("project_due_date") or {}
    due_line = _clean(due.get("effective_date"))
    if due.get("source") and due.get("source") != "Not specified":
        due_line = f"{due_line} (source: {due['source']})"
    if due.get("conflict"):
        due_line += (
            " — the uploaded document states a different date, which takes precedence "
            "over the date entered on the project record"
        )
    doc.add_paragraph(f"Project Due Date: {due_line}")
    doc.add_paragraph(
        f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}"
    )
    doc.add_paragraph(f"Basis: {basis}")
    doc.add_paragraph(
        "Generated by the Documentation Generation Agent from the project's "
        "own uploaded documents and existing analysis output. It does not "
        "replace, and never overwrites, the original uploaded files."
    )


def _validation_block(doc, data: dict) -> None:
    validation = data.get("validation") or {}
    if not validation:
        return
    _heading(doc, "Validation and corrections", level=1)
    doc.add_paragraph(
        f"Status: {validation.get('status', NOT_SPECIFIED)} — "
        f"{validation.get('fields_checked', 0)} fields checked, "
        f"{validation.get('supported', 0)} supported by project data, "
        f"{validation.get('corrected', 0)} corrected, "
        f"{validation.get('unsupported_removed', 0)} removed as unsupported, "
        f"{validation.get('not_specified', 0)} not specified in project data, "
        f"{validation.get('conflicts', 0)} conflicts recorded."
    )
    findings = [
        f for f in (validation.get("findings") or [])
        if f.get("verdict") not in (None, "SUPPORTED")
    ]
    if findings:
        _table(
            doc,
            ["Field", "Verdict", "Value kept", "Explanation"],
            [
                [
                    f.get("field") or NOT_SPECIFIED,
                    VERDICT_LABELS.get(f.get("verdict"), f.get("verdict") or NOT_SPECIFIED),
                    f.get("value") or NOT_SPECIFIED,
                    f.get("note") or "",
                ]
                for f in findings
            ],
        )
        doc.add_paragraph()


def _notes_block(doc, notes: list[str] | None) -> None:
    if not notes:
        return
    _heading(doc, "Generation notes", level=1)
    for note in notes:
        doc.add_paragraph(note, style="List Bullet")


