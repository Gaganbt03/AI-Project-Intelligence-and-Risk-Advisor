def _user_stories(doc, data: dict) -> None:
    stories = data.get("stories") or []
    doc.add_paragraph(f"{len(stories)} grounded user stories.")
    for story in stories:
        _heading(doc, f"{story['id']} · {story['title']}", level=1)
        doc.add_paragraph(
            f"As a {story.get('as_a') or story.get('role')}, "
            f"I want {_clean(story.get('i_want') or story.get('goal'))}, "
            f"so that {_clean(story.get('so_that') or story.get('benefit'))}."
        )
        _kv(doc, "Priority", story.get("priority"))
        _kv(doc, "Status", story.get("status"))
        _kv(doc, "Related requirement", story.get("related_requirement"))
        _kv(doc, "Source document", story.get("source_document"))
        if not _is_placeholder(story.get("source_evidence")):
            _kv(doc, "Source evidence", story.get("source_evidence"), mono=True)
        criteria = story.get("acceptance_criteria") or []
        if criteria:
            _heading(doc, "Acceptance criteria", level=2)
            for criterion in criteria:
                doc.add_paragraph(criterion, style="List Bullet")
        else:
            doc.add_paragraph(
                f"Acceptance criteria: {NOT_SPECIFIED} — no stated criterion could be traced "
                "to the project documents."
            )


def _risk_register(doc, data: dict) -> None:
    entries = data.get("entries") or []
    doc.add_paragraph(
        f"{len(entries)} risks · total exposure {data.get('total_exposure', 0)} · "
        f"highest score {data.get('max_score', 0)}/25"
    )
    if entries:
        _table(
            doc,
            ["Risk ID", "Title", "Category", "Probability", "Impact", "Score", "Severity", "Status"],
            [
                [
                    e["risk_id"],
                    e["title"],
                    e.get("category"),
                    e.get("probability"),
                    e.get("impact"),
                    f"{e['risk_score']}/25",
                    e.get("severity_band"),
                    e.get("status"),
                ]
                for e in entries
            ],
        )
        doc.add_paragraph()
    else:
        doc.add_paragraph(
            f"{NOT_SPECIFIED} No risk records exist for this project, so the register is empty."
        )

    for entry in entries:
        _heading(doc, f"{entry['risk_id']} · {entry['title']}", level=1)
        _kv(doc, "Description", entry.get("description"))
        _kv(doc, "Category", entry.get("category"))
        _kv(doc, "Probability", entry.get("probability"))
        _kv(doc, "Impact", entry.get("impact"))
        _kv(doc, "Risk score", f"{entry['risk_score']}/25 ({_clean(entry.get('severity_band'))})")
        _kv(doc, "Severity", entry.get("severity"))
        _kv(doc, "Status", entry.get("status"))
        _kv(doc, "Owner", entry.get("owner"))
        _kv(doc, "Mitigation", entry.get("mitigation"))
        _kv(doc, "Contingency", entry.get("contingency"))
        _relationship(doc, "Related blockers", entry.get("related_blockers"))
        _relationship(doc, "Related actions", entry.get("related_actions"))
        _kv(doc, "Source document", entry.get("source_document"))
        if not _is_placeholder(entry.get("source_evidence")):
            _kv(doc, "Evidence", entry.get("source_evidence"), mono=True)
        for conflict in entry.get("conflicts") or []:
            paragraph = doc.add_paragraph(style="List Bullet")
            _run(paragraph, f"Conflict: {conflict}")

    excluded = data.get("excluded") or []
    if excluded:
        _heading(doc, "Records kept in their own category", level=1)
        doc.add_paragraph(
            "These rows live in the recorded risk table but are described by the source "
            "documents as blockers or action items. They are listed for traceability and are "
            "not counted as risks."
        )
        _table(
            doc,
            ["Record", "Description", "Classified as", "Reason", "Kept in"],
            [
                [
                    item.get("risk_id"),
                    item.get("title"),
                    item.get("classified_as"),
                    item.get("reason"),
                    item.get("kept_in"),
                ]
                for item in excluded
            ],
        )


def _action_items(doc, data: dict) -> None:
    entries = data.get("entries") or []
    doc.add_paragraph(
        f"{data.get('open', 0)} open of {data.get('total', 0)} · "
        f"{data.get('ai_generated', 0)} AI-generated · "
        f"{data.get('unassigned_count', 0)} without an owner · "
        f"{data.get('missing_due_date_count', 0)} open without a due date"
    )
    if entries:
        _table(
            doc,
            ["Action ID", "Action", "Owner", "Priority", "Due", "Status", "Origin", "Source"],
            [
                [
                    e["action_id"],
                    e["action"],
                    e.get("owner"),
                    e.get("priority"),
                    e.get("due_date"),
                    e.get("status"),
                    e.get("origin"),
                    e.get("source_document"),
                ]
                for e in entries
            ],
        )
        doc.add_paragraph()
    else:
        doc.add_paragraph(
            f"{NOT_SPECIFIED} No tasks or blockers are recorded for this project, so the list "
            "is empty."
        )

    for entry in entries:
        _heading(doc, f"{entry['action_id']} · {entry['action']}", level=1)
        _kv(doc, "Description", entry.get("description"))
        _kv(doc, "Owner", entry.get("owner"))
        _kv(doc, "Priority", entry.get("priority"))
        _kv(doc, "Due date", entry.get("due_date"))
        _kv(doc, "Status", entry.get("status"))
        _kv(doc, "Related risk", entry.get("related_risk"))
        _kv(doc, "Related blocker", entry.get("related_blocker"))
        _kv(doc, "Origin", entry.get("origin"))
        _kv(doc, "Source document", entry.get("source_document"))
        if not _is_placeholder(entry.get("source_evidence")):
            _kv(doc, "Source evidence", entry.get("source_evidence"), mono=True)

        trace = entry.get("due_date_trace") or {}
        if trace:
            _heading(doc, "Due date traceability", level=2)
            _kv(doc, "Administrator-entered date", trace.get("admin_date"))
            _kv(doc, "Date in the source document", trace.get("document_date"))
            _kv(doc, "Effective date", trace.get("effective_date"))
            _kv(doc, "Precedence applied", trace.get("source"))
            _kv(
                doc,
                "Conflict with the administrator-entered date",
                "Yes" if trace.get("conflict") else "No",
            )


_BUILDERS = {
    DOC_USER_STORIES: (_user_stories, "existing uploaded project documents (RAG) + "
                                        "Scope Analysis output"),
    DOC_RISK_REGISTER: (_risk_register, "existing Risk Detection output "
                                        "+ project documents"),
    DOC_ACTION_ITEMS: (_action_items, "existing tasks, AI-detected action items and open blockers"),
}


DOC_TITLES = {
    "user_stories": "PROJECT USER STORIES",
    "risk_register": "PROJECT RISK REGISTER",
    "action_items": "PROJECT ACTION ITEMS",
}


def build_docx(doc_type: str, data: dict, project_name: str) -> bytes:
    """Return the DOCX bytes for one stored payload.

    >>> build_docx("risk_register", {"entries": []}, "Demo")[:2]  # doctest: +ELLIPSIS
    b'PK'
    """
    entry = _BUILDERS.get(doc_type)
    if entry is None:
        raise ValueError(f"Unknown documentation type: {doc_type}")
    builder, basis = entry

    doc = Document()
    style = doc.styles["Normal"]
    style.font.size = Pt(10.5)

    _header_block(
        doc,
        DOC_TITLES.get(doc_type) or data.get("title") or doc_type.replace("_", " ").title(),
        project_name,
        basis,
        data,
    )

    if data.get("insufficient_evidence"):
        doc.add_paragraph(str(data.get("reason") or NOT_SPECIFIED))
    else:
        builder(doc, data)

    _validation_block(doc, data)
    _notes_block(doc, data.get("notes"))
    doc.add_paragraph(
        f"Exported {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} from the stored "
        "generated document."
    )

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


